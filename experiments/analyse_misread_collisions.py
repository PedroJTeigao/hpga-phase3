"""Post hoc, descriptive: on MISREAD lines, is NEW equal to the true letter at chance? (results/MISREAD_COLLISIONS.md)

Data: first attempts of the OLD-slot cells, both displays. Spaced = the OLD-slot gate's new-format cells
(results/raw/oldfield_gate/calls_<model>_<C2|C3>_new.jsonl); numbered = the numbered probe's numbered+OLD cells
(results/raw/numbered_probe/calls_<model>_<C2|C3>_numold.jsonl). A line is misread when its stated OLD differs from the
letter actually at that position; only misread lines are kept, and an attempt with no misread line is dropped.

Baselines: experiments/analyse_blind_choice.py's measure(), unchanged, applied to the misread lines as the data set:
"marginal" (this data set's own NEW-letter distribution) and "shuffle" (lines re-paired with other attempts' sequences
from the same data set, 200 pairings). BLIND_CHOICE.md uses the shuffle baseline for its readings; it is reported first.
Two-sided exact binomial p of the observed repeat count against n lines at each baseline's expected rate.

  python experiments/analyse_misread_collisions.py  -> results/raw/misread_collisions.json, results/raw/misread_collisions_tables.md
"""

import json
import math
import random
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import analyse_blind_choice as bc  # noqa: E402
import probe_mutate_numbered as pn  # noqa: E402  (sequence_of: reads the genome from either display)

ROOT = HERE.parent
MODELS = ("gemma4_12b", "qwen2.5_7b", "mistral_7b", "llama3.2_3b")
PON = re.compile(r"POSITION\s*:\s*(\d+)\s*,\s*OLD\s*:\s*([A-Za-z])\s*,\s*NEW\s*:\s*([A-Za-z])", re.I)
FILES = {"spaced": ROOT / "results/raw/oldfield_gate/calls_{m}_{c}_new.jsonl",
         "numbered": ROOT / "results/raw/numbered_probe/calls_{m}_{c}_numold.jsonl"}


def misread_attempts(path: Path) -> list[tuple[str, list[tuple[int, str]]]]:
    out = []
    for line in open(path):
        r = json.loads(line)
        if "prompt" not in r or r.get("attempt") != 0:
            continue
        g = pn.sequence_of(r["prompt"])
        lines = [(int(p), n.upper()) for p, o, n in PON.findall(r["response"]) if int(p) < len(g) and o.upper() != g[int(p)]]
        if lines:
            out.append((g, lines))
    return out


def binom_two_sided(k: int, n: int, p: float) -> float:
    """Exact two-sided binomial p: total probability of outcomes no more likely than the observed one."""
    if n == 0:
        return float("nan")
    pmf = [math.comb(n, i) * p ** i * (1 - p) ** (n - i) for i in range(n + 1)]
    return min(1.0, sum(x for x in pmf if x <= pmf[k] * (1 + 1e-9)))


def main() -> None:
    rng = random.Random(0)
    res, md = {}, []
    for m in MODELS:
        for c in ("C2", "C3"):
            for disp, tmpl in FILES.items():
                att = misread_attempts(Path(str(tmpl).format(m=m, c=c)))
                if not att:
                    res[f"{m}|{c}|{disp}"] = {"lines": 0}
                    continue
                try:
                    r = bc.measure(att, rng)
                except ZeroDivisionError:  # marginal expectation exactly 0 in a tiny cell: measure() cannot form the ratio
                    n = sum(len(ls) for _, ls in att)
                    k = sum(g[a] == b for g, ls in att for a, b in ls)
                    res[f"{m}|{c}|{disp}"] = {"lines": n, "observed": k, "undefined": "baseline expectation 0 (too few lines)"}
                    continue
                n, k = r["lines"], r["observed"]
                r["p_shuffle"] = binom_two_sided(k, n, r["shuffle_rate"])
                r["p_marginal"] = binom_two_sided(k, n, r["marginal_rate"])
                res[f"{m}|{c}|{disp}"] = r
    json.dump(res, open(ROOT / "results/raw/misread_collisions.json", "w"), indent=1)
    md += ["# Misread-line collisions (generated by experiments/analyse_misread_collisions.py; post hoc, descriptive)", "",
           "| model | cond | display | n misread lines | observed | shuffle expected [95% range] | ratio, p (shuffle) | marginal expected | ratio, p (marginal) |",
           "|---|---|---|---|---|---|---|---|---|"]
    for key, r in res.items():
        m, c, disp = key.split("|")
        if not r["lines"] or "undefined" in r:
            md.append(f"| {m} | {c} | {disp} | {r['lines']} | {r.get('observed', '')} | {r.get('undefined', 'no misread lines')} | | | |")
            continue
        lo, hi = r["shuffle_rate_95"]
        md.append(f"| {m} | {c} | {disp} | {r['lines']} | {r['observed']} ({r['observed_rate']:.3f}) | {r['shuffle_rate']:.3f} [{lo:.3f}, {hi:.3f}] | "
                  f"{r['ratio_shuffle']:.2f}, p={r['p_shuffle']:.3g} | {r['marginal_rate']:.3f} | {r['ratio_marginal']:.2f}, p={r['p_marginal']:.3g} |")
    (ROOT / "results/raw/misread_collisions_tables.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
