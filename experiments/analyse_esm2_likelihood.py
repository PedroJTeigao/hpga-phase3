"""Tables for results/ESM2_LIKELIHOOD_SCREEN.md from results/raw/esm2_likelihood_*.json.

Does ESM-2 150M's preference predict realised TM-score gain? Three questions:

  1. dlogit (the model's preference for the substitution, in the base's context) vs realised gain.
  2. dPLL (whole-sequence likelihood change) vs realised gain; covers the indels too.
  3. Mean per-position log-likelihood of a base genome vs that genome's own fitness, with the
     breeding-step confound checked, since both quantities drift as the GA advances.

No scipy in this venv, so Pearson and Spearman are computed here. p is a two-sided NORMAL
APPROXIMATION on Fisher's z, uncorrected for multiple comparisons: 20 tests are reported in
sections 1-2 alone (5 arms x 2 metrics x 2 coefficients), so nominal p < 0.05 means little,
and the sign consistency across arms is the thing to read.

    /scratch/pcanaste/venv/bin/python experiments/analyse_esm2_likelihood.py
"""

import glob
import json
import math
import statistics as st
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "results" / "raw"
ARMS = ("S1", "S2", "S3", "S4", "B")
HDR = ("| subset | n | Pearson r | p~ | Spearman rho | p~ |\n|---|---|---|---|---|---|")


def pearson(x, y):
    n = len(x)
    if n < 4:
        return None, None, n
    mx, my = st.mean(x), st.mean(y)
    sx = math.sqrt(sum((a - mx) ** 2 for a in x))
    sy = math.sqrt(sum((b - my) ** 2 for b in y))
    if sx == 0 or sy == 0:
        return None, None, n
    r = sum((a - mx) * (b - my) for a, b in zip(x, y)) / (sx * sy)
    r = max(-0.999999, min(0.999999, r))
    z = 0.5 * math.log((1 + r) / (1 - r)) * math.sqrt(n - 3)  # Fisher, normal approximation
    return r, math.erfc(abs(z) / math.sqrt(2)), n


def rank(v):
    order = sorted(range(len(v)), key=lambda i: v[i])
    rk, i = [0.0] * len(v), 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and v[order[j + 1]] == v[order[i]]:
            j += 1
        for k in range(i, j + 1):
            rk[order[k]] = (i + j) / 2 + 1
        i = j + 1
    return rk


def spearman(x, y):
    return pearson(rank(x), rank(y))


def row(label, x, y):
    r, p, n = pearson(x, y)
    rs, ps, _ = spearman(x, y)
    if r is None:
        return f"| {label} | {n} | – | – | – | – |"
    return f"| {label} | {n} | {r:+.3f} | {p:.2g} | {rs:+.3f} | {ps:.2g} |"


def main():
    moves, native = [], None
    for f in sorted(glob.glob(str(RAW / "esm2_likelihood_*.json"))):
        d = json.load(open(f))
        native = d["native_reference_mean_ll"]
        for m in d["moves"]:
            moves.append({**m, "arm": d["arm"], "seed": d["seed"]})
    print(f"# ESM-2 likelihood screen: generated tables\n\nGenerated by "
          f"experiments/analyse_esm2_likelihood.py from results/raw/esm2_likelihood_*.json. "
          f"Read with results/ESM2_LIKELIHOOD_SCREEN.md.\n\nmoves: {len(moves)}")

    L = []
    for metric, title in (("dlogit", "Δlogit at changed positions (substitution arms only)"),
                          ("dPLL", "ΔPLL = PLL(child) − PLL(base) (all arms, indels included)")):
        sub = [m for m in moves if m[metric] is not None]
        L += ["", f"## {metric}: {title} vs realised fitness gain", "", HDR,
              row("**pooled**", [m[metric] for m in sub], [m["gain"] for m in sub])]
        for a in ARMS:
            s = [m for m in sub if m["arm"] == a]
            if s:
                L.append(row(a, [m[metric] for m in s], [m["gain"] for m in s]))
        for lab, f in (("improved only", lambda m: m["improved"]),
                       ("not improved", lambda m: not m["improved"])):
            s = [m for m in sub if f(m)]
            L.append(row(f"pooled, {lab}", [m[metric] for m in s], [m["gain"] for m in s]))

        nz = [m for m in sub if m[metric] != 0]
        agree = sum(1 for m in nz if (m[metric] > 0) == (m["gain"] > 0))
        up = [m for m in sub if m[metric] > 0]
        dn = [m for m in sub if m[metric] < 0]
        iu, idn = sum(m["improved"] for m in up), sum(m["improved"] for m in dn)
        L += ["", f"- sign agreement: {agree}/{len(nz)} = {100 * agree / len(nz):.1f}%",
              f"- moves the model prefers (Δ>0): {len(up)}, improved {iu} "
              f"({100 * iu / max(1, len(up)):.1f}%)",
              f"- moves the model dislikes (Δ<0): {len(dn)}, improved {idn} "
              f"({100 * idn / max(1, len(dn)):.1f}%)"]

    # --- base genome likelihood vs its own fitness, and the breeding-step confound
    seen = {}
    for m in moves:
        seen.setdefault((m["arm"], m["seed"], m["mean_ll_base"], m["base_fitness"]), m)
    B = list(seen.values())
    L += ["", "## Base genome: mean per-position log-likelihood vs its own TM fitness", "", HDR,
          row("**pooled unique (arm,seed,base)**",
              [m["mean_ll_base"] for m in B], [m["base_fitness"] for m in B])]
    for a in ARMS:
        s = [m for m in B if m["arm"] == a]
        L.append(row(a, [m["mean_ll_base"] for m in s], [m["base_fitness"] for m in s]))
    for sd in sorted({m["seed"] for m in B}):
        s = [m for m in B if m["seed"] == sd]
        L.append(row(f"seed {sd} (all arms)", [m["mean_ll_base"] for m in s],
                     [m["base_fitness"] for m in s]))

    L += ["", "### The breeding-step confound", "",
          "Bases come from an evolving population, so both quantities drift with step:", "",
          "| quantity vs breeding step | n | r | p~ |", "|---|---|---|---|"]
    for lab, key in (("mean per-position LL", "mean_ll_base"), ("base TM fitness", "base_fitness")):
        r, p, n = pearson([m["step"] for m in B], [m[key] for m in B])
        L.append(f"| {lab} | {n} | {r:+.3f} | {p:.2g} |")
    L += ["", "Conditioning on step (thirds as in MOVE_CLASS.md §4, then single steps):", "",
          "| LL vs fitness, within band | n | r | p~ |", "|---|---|---|---|"]
    for lo, hi, lab in ((0, 6, "early 0–5"), (6, 12, "middle 6–11"), (12, 19, "late 12–18")):
        s = [m for m in B if lo <= m["step"] < hi]
        r, p, n = pearson([m["mean_ll_base"] for m in s], [m["base_fitness"] for m in s])
        L.append(f"| {lab} | {n} | {r:+.3f} | {p:.2g} |")
    for stp in (0, 9, 18):
        s = [m for m in B if m["step"] == stp]
        r, p, n = pearson([m["mean_ll_base"] for m in s], [m["base_fitness"] for m in s])
        L.append(f"| single step {stp} | {n} | {r:+.3f} | {p:.2g} |")

    ll = [m["mean_ll_base"] for m in B]
    fit = [m["base_fitness"] for m in B]
    L += ["", "### Calibration against the native sequence", "",
          f"- native 7UR7 chain A (the fitness reference): mean per-position LL **{native:.3f}**",
          f"- the {len(B)} unique GA bases: mean {st.mean(ll):.3f}, min {min(ll):.3f}, "
          f"max {max(ll):.3f}",
          f"- their TM fitness: mean {st.mean(fit):.4f}, min {min(fit):.4f}, max {max(fit):.4f}",
          f"- bases scoring above the native sequence: "
          f"{sum(1 for v in ll if v > native)} of {len(ll)}"]

    out = ROOT / "results" / "ESM2_LIKELIHOOD_TABLES.md"
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"\nwrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
