"""Tables for results/INDEXING_NOT_INSTRUCTION.md, from existing files only (no model calls).

  1. Core table: in the OLD-slot gate's new-format lines (results/raw/oldfield_gate, all conditions, all attempts),
     repeats of the current letter split by whether the model stated the letter at that position (OLD) correctly.
  2. Reading accuracy (OLD correct / lines) per model, by condition (C1 = 1 change per call, C2/C3 = 3 or 2-4) and by
     position band 0-9 / 10-19 / 20+.
  3. Old-format repeat ratio in the gate's cells against shuffle chance (experiments/analyse_blind_choice.py's method).
  4. GA logs, production format, first attempts: repeat rate by position band against the marginal chance rate.

  python experiments/analyse_position_reading.py  -> results/raw/position_reading.json, results/raw/position_reading_tables.md
"""

import collections
import json
import random
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import analyse_blind_choice as bc  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
GATE = ROOT / "results" / "raw" / "oldfield_gate"
MODELS = ("gemma4_12b", "qwen2.5_7b", "mistral_7b", "llama3.2_3b")
CONDS = ("C1", "C2", "C3")
BANDS = ("0-9", "10-19", "20+")
SEQ = re.compile(r"positions 0-\d+\): ([A-Z ]+)")
PON = re.compile(r"POSITION\s*:\s*(\d+)\s*,\s*OLD\s*:\s*([A-Za-z])\s*,\s*NEW\s*:\s*([A-Za-z])", re.I)


def band(p: int) -> str:
    return "0-9" if p < 10 else "10-19" if p < 20 else "20+"


def new_format_lines(model: str, cond: str):
    for line in open(GATE / f"calls_{model}_{cond}_new.jsonl"):
        r = json.loads(line)
        if "prompt" not in r:
            continue
        g = "".join(SEQ.search(r["prompt"]).group(1).split())
        for p, o, n in PON.findall(r["response"]):
            p = int(p)
            if p < len(g):
                yield g, p, o.upper(), n.upper()


def main() -> None:
    res, md = {"core": {}, "reading": {}, "gate_old_ratio": {}, "ga_bands": {}}, []
    for m in MODELS:
        c = collections.Counter()
        acc = collections.defaultdict(lambda: [0, 0])
        for cond in CONDS:
            for g, p, o, n in new_format_lines(m, cond):
                ok = o == g[p]
                c["ok"] += ok
                c["ok_rep"] += ok and n == g[p]
                c["wrong"] += not ok
                c["wrong_rep"] += (not ok) and n == g[p]
                for key in ((cond, band(p)), (cond, "all"), ("all", band(p)), ("all", "all")):
                    acc[key][0] += ok
                    acc[key][1] += 1
        res["core"][m] = dict(c)
        res["reading"][m] = {f"{a}|{b}": v for (a, b), v in acc.items()}
    rng = random.Random(0)
    for m in MODELS:
        res["gate_old_ratio"][m] = {}
        for cond in CONDS:
            r = bc.measure(bc.attempts([GATE / f"calls_{m}_{cond}_old.jsonl"], True), rng)
            res["gate_old_ratio"][m][cond] = {k: r[k] for k in ("lines", "observed", "observed_rate", "shuffle_rate", "ratio_shuffle")}
    ga = {"gemma4:12b arm C": range(5), "gemma4:12b arm F": range(3), "qwen2.5:7b arm C": range(5)}
    for name, seeds in ga.items():
        att = bc.attempts([p for s in seeds for p in bc.ga_logs(name, s)], True)
        newc = collections.Counter(b for _, ls in att for _, b in ls)
        tot = sum(newc.values())
        st = {b: [0, 0, 0.0] for b in BANDS}
        for g, ls in att:
            for a, b in ls:
                s = st[band(a)]
                s[0] += 1
                s[1] += g[a] == b
                s[2] += newc[g[a]] / tot
        res["ga_bands"][name] = {b: {"lines": s[0], "repeats": s[1], "rate": s[1] / s[0], "chance": s[2] / s[0],
                                     "ratio": s[1] / s[2]} for b, s in st.items()}
    json.dump(res, open(ROOT / "results" / "raw" / "position_reading.json", "w"), indent=1)

    md += ["# Position-reading tables (generated by experiments/analyse_position_reading.py)", "",
           "## 1. Repeats of the current letter, by whether OLD was stated correctly (gate, new format, all conditions, all attempts)", "",
           "| model | OLD correct: lines | of which NEW = current letter | OLD wrong: lines | of which NEW = actual letter (rate) |",
           "|---|---|---|---|---|"]
    tot = collections.Counter()
    for m, c in res["core"].items():
        tot.update(c)
        md.append(f"| {m} | {c['ok']} | {c['ok_rep']} | {c['wrong']} | {c['wrong_rep']} ({c['wrong_rep'] / c['wrong']:.3f}) |")
    md += [f"| all | {tot['ok']} | {tot['ok_rep']} | {tot['wrong']} | {tot['wrong_rep']} ({tot['wrong_rep'] / tot['wrong']:.3f}) |", "",
           "## 2. Reading accuracy (OLD correct / lines), by condition and position band", "",
           "| model | condition | 0-9 | 10-19 | 20+ | all |", "|---|---|---|---|---|---|"]
    for m, d in res["reading"].items():
        for cond in CONDS + ("all",):
            cells = []
            for b in BANDS + ("all",):
                ok, n = d.get(f"{cond}|{b}", [0, 0])
                cells.append(f"{ok}/{n} = {ok / n:.2f}" if n else "0/0")
            md.append(f"| {m} | {cond} | " + " | ".join(cells) + " |")
    md += ["", "## 3. Old (production) format in the gate: repeat ratio against shuffle chance (first attempts)", "",
           "| model | C1 (k = 1) | C2 (k = 3, random) | C3 (k = 2-4, replayed GA sequences) |", "|---|---|---|---|"]
    for m, d in res["gate_old_ratio"].items():
        md.append(f"| {m} | " + " | ".join(f"{d[c]['observed']}/{d[c]['lines']}, ratio {d[c]['ratio_shuffle']:.2f}" for c in CONDS) + " |")
    md += ["", "## 4. GA logs, production format, first attempts: repeat rate by position band (ratio against marginal chance)", "",
           "| data set | 0-9 | 10-19 | 20+ |", "|---|---|---|---|"]
    for name, d in res["ga_bands"].items():
        md.append(f"| {name} | " + " | ".join(f"{d[b]['repeats']}/{d[b]['lines']} = {d[b]['rate']:.3f} (chance {d[b]['chance']:.3f}, ratio {d[b]['ratio']:.2f})" for b in BANDS) + " |")
    (ROOT / "results" / "raw" / "position_reading_tables.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
