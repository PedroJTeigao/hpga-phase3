"""Recount, from committed raw logs only, the conditional result "a correctly read line never repeats the letter" in all
three experiments that measured it, on both attempt scopes, so that the three counts can be put on one footing.

The published figures are on different scopes: 3,784 (OLD-slot gate, INDEXING_NOT_INSTRUCTION.md Evidence 1) is all
attempts; 4,440 (numbered probe, PREREGISTERED_NUMBERED_SCORED.md rule 3(b)) and 2,025 (SPARK_QWEN35_PROBE.md) are first
attempts. A recount of existing data, not a new result. No model calls.

Line definition, identical in all three (as in analyse_position_reading.py:36-46 and probe_mutate_numbered.py:212-223):
a `POSITION, OLD, NEW` line with position < sequence length; "correctly read" = OLD equals the letter at that position;
"repeat" = NEW equals that letter too.

  python experiments/recount_conditional_repeats.py   -> results/CONDITIONAL_REPEATS_RECOUNT_TABLES.md
"""

import collections
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "results" / "raw"
SEQ = re.compile(r"positions 0-\d+\): ((?:\d+:)?[A-Z](?: (?:\d+:)?[A-Z])*)\n")
PON = re.compile(r"POSITION\s*:\s*(\d+)\s*,\s*OLD\s*:\s*([A-Za-z])\s*,\s*NEW\s*:\s*([A-Za-z])", re.I)
MODELS = ("gemma4_12b", "qwen2.5_7b", "mistral_7b", "llama3.2_3b")
SPARK = "nvidia_Qwen3.6-35B-A3B-NVFP4"

# experiment -> list of (model, cell label, file)
SOURCES = {
    "OLD-slot gate (spaced display)": [(m, c, RAW / "oldfield_gate" / f"calls_{m}_{c}_new.jsonl") for m in MODELS for c in ("C1", "C2", "C3")],
    "numbered probe (numbered display)": [(m, c, RAW / "numbered_probe" / f"calls_{m}_{c}_numold.jsonl") for m in MODELS for c in ("C2", "C3")],
    "Spark run, nvidia/Qwen3.6-35B-A3B-NVFP4 (both displays)": (
        [(SPARK, f"spaced {c}", RAW / "spark_qwen" / "oldfield_gate_spark_qwen" / f"calls_{SPARK}_{c}_new.jsonl") for c in ("C1", "C2", "C3")]
        + [(SPARK, f"numbered {c}", RAW / "spark_qwen" / "numbered_probe_spark_qwen" / f"calls_{SPARK}_{c}_numold.jsonl") for c in ("C2", "C3")]),
}


def count(path: Path) -> dict:
    out = {s: collections.Counter() for s in ("first", "all")}
    for line in open(path):
        r = json.loads(line)
        if "response" not in r:
            continue
        g = "".join(t.split(":")[-1] for t in SEQ.search(r["prompt"]).group(1).split())
        for p, o, n in PON.findall(r["response"]):
            p = int(p)
            if p >= len(g):
                continue
            ok = o.upper() == g[p]
            for s in (("first", "all") if r["attempt"] == 0 else ("all",)):
                out[s]["read"] += ok
                out[s]["repeat"] += ok and n.upper() == g[p]
    return out


def main() -> None:
    md = ["# Conditional repeats, recounted on both attempt scopes (generated by experiments/recount_conditional_repeats.py)", "",
          "Lines with OLD stated correctly, and of those, lines whose NEW equals that same letter. "
          "Recount of committed raw logs; no model calls. The Spark model is nvidia/Qwen3.6-35B-A3B-NVFP4, "
          "not a controlled model-scale comparison (results/SPARK_QWEN35_PROBE.md).", "",
          "| experiment | model | cell | first attempts: read correctly | repeats | all attempts: read correctly | repeats |",
          "|---|---|---|---|---|---|---|"]
    totals = {}
    for exp, srcs in SOURCES.items():
        t = {s: collections.Counter() for s in ("first", "all")}
        for m, c, path in srcs:
            k = count(path)
            for s in t:
                t[s].update(k[s])
            md.append(f"| {exp} | {m} | {c} | {k['first']['read']} | {k['first']['repeat']} | {k['all']['read']} | {k['all']['repeat']} |")
        md.append(f"| **{exp}, total** | | | **{t['first']['read']}** | **{t['first']['repeat']}** | **{t['all']['read']}** | **{t['all']['repeat']}** |")
        totals[exp] = t
    md += ["", "| scope | " + " | ".join(totals) + " | combined |", "|---|" + "---|" * (len(totals) + 1)]
    for s in ("first", "all"):
        md.append(f"| {s} attempts | " + " | ".join(f"{t[s]['repeat']} of {t[s]['read']}" for t in totals.values())
                  + f" | {sum(t[s]['repeat'] for t in totals.values())} of {sum(t[s]['read'] for t in totals.values())} |")
    text = "\n".join(md) + "\n"
    (ROOT / "results" / "CONDITIONAL_REPEATS_RECOUNT_TABLES.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
